
/*Дано целое число n, которое может оказаться k-ой ЦЕЛОЙ степенью другого ЦЕЛОГО числа.
Дано: n = a^k (n равно a в степени k)
Написать программу,
для выяснения для какого другого целого числа данное n является k-ой ЦЕЛОЙ степенью.
Нужно: найти число a (корень k-й степени из n)
Входные данные: два целых числа через пробел n k.
Выходные данные: отладочная печать - поиск сомножителей.
Первая строка - наименьший сомножитель корня a1a1​, частное от деления на a1ka1k​ 
первый сомножитель в степени k .
Вторая строка -- второй предполагаемый сомножитель корня a2a2​,
частное от деления n на a1⋅a2)ka1​⋅a2​)k первый и второй сомножителя в степени k.
И так далее до тех пор пока могут быть найдены сомножители степени k.
Последняя строка: если k - степень числа n, печатается корень, если нет -1
Ищем наименьший множитель a₁, такой что a₁^k делит n
Ищем следующий множитель a₂ из остатка
Остаток = 1 → нашли все множители*/
#include <stdio.h>

int main()
{
    unsigned long long n;
    int k;
    unsigned long long root = 1;
    unsigned long long temp;
    int found_any = 0;  // флаг

    scanf("%llu %d", &n, &k);
    temp = n;

    // Ищем множители начиная с 2
    for (unsigned long long i = 2; i * i <= temp; i++) {
        unsigned long long power = 1;
        
        // Вычисляем i^k
        for (int j = 0; j < k; j++) {
            power *= i;
        }
        
        // Пока i^k делит temp
        while (temp % power == 0) {
            temp /= power;
            printf("%llu %llu\n", i, temp);   
            root *= i;            // Копим корень
            found_any = 1;
        }
    }

    // Если что-то нашли и остаток = 1
    if (found_any && temp == 1) {
        printf("%llu\n", root);  // Печатаем корень
    } else {
        printf("-1\n");  // Не является k-й степенью
    }

    return 0;
}